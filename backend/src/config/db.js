const { Pool } = require('pg');

if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required.');

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : undefined,
  max: 5,
});

function postgresQuery(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

async function createSchema() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS categories (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE(user_id, name)
    );
    CREATE TABLE IF NOT EXISTS transactions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
      description TEXT NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK(amount > 0),
      type TEXT NOT NULL CHECK(type IN ('income', 'expense')), date DATE NOT NULL, notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS goals (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL, target_amount NUMERIC(14,2) NOT NULL CHECK(target_amount > 0),
      current_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(current_amount >= 0), target_date DATE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id, date DESC);
    CREATE INDEX IF NOT EXISTS idx_transactions_user_type ON transactions(user_id, type);
    CREATE INDEX IF NOT EXISTS idx_goals_user ON goals(user_id);
  `);
}

const ready = createSchema();
const db = {
  prepare(sql) {
    const text = postgresQuery(sql);
    return {
      async get(...params) { await ready; return (await pool.query(text, params)).rows[0]; },
      async all(...params) { await ready; return (await pool.query(text, params)).rows; },
      async run(...params) {
        await ready;
        const statement = /^\s*insert\s/i.test(text) && !/\breturning\b/i.test(text) ? `${text} RETURNING id` : text;
        const result = await pool.query(statement, params);
        return { lastInsertRowid: result.rows[0]?.id, changes: result.rowCount };
      },
    };
  },
  pool,
  ready,
};

async function ensureUserDefaultCategories(userId) {
  const names = ['Salário', 'Freelance', 'Alimentação', 'Moradia', 'Transporte', 'Saúde', 'Educação', 'Entretenimento', 'Outros'];
  await ready;
  for (const name of names) {
    await pool.query('INSERT INTO categories (user_id, name) VALUES ($1, $2) ON CONFLICT (user_id, name) DO NOTHING', [userId, name]);
  }
}

module.exports = { db, ensureUserDefaultCategories };
